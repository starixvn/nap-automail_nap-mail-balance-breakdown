using Fanex.BalanceBreakdown.Business.Models;
using OfficeOpenXml;
using System;
using System.Collections.Generic;
using System.Data;
using System.IO;
using System.Linq;

namespace Fanex.BalanceBreakdown.Business.Services;

public interface ExcelService
{
    void Export(bool isDaily);
}

public class ExcelServiceImp : ExcelService
{
    private readonly DataService dataService;

    public ExcelServiceImp(
        DataService dataService
    )
    {
        this.dataService = dataService;
    }

    public void Export(bool isDaily)
    {
        var totalList = new List<TotalModel>();
        var counter = 1;
        while (true)
        {
            using var reader = dataService.QueryData(isDaily, counter - 1, AppConfigService.Config.PageSize);
            using var excelPackage = new ExcelPackage(new FileInfo("Templates/Template.xlsx"));
            using var formatTpl = excelPackage.Workbook.Worksheets["Format"];
            using var sheet = excelPackage.Workbook.Worksheets.Add($"Bal-{counter}");

            RenderTitle(isDaily, sheet, formatTpl);
            RenderContent(reader, sheet, formatTpl, out var hasData, out var total);
            if (!hasData)
            {
                excelPackage.Workbook.Worksheets.Delete(sheet);
                RenderBallDiff(isDaily, excelPackage, totalList, formatTpl);
                return;
            }

            var fileName = isDaily
                ? $"Daily Balance Breakdown {counter} for {DateTime.Today:dd-MM-yyyy}.xlsx"
                : $"Monthly Balance Breakdown {counter} for {DateTime.Today.AddMonths(-1):yyyy-MM}.xlsx";

            SaveExcelFile(isDaily, excelPackage, fileName);

            totalList.Add(new TotalModel
            {
                Name = $"Bal-{counter}",
                TotalRM = total
            });
            counter++;

            CollectGarbage();
        }
    }

    private static void CollectGarbage()
    {
        for (var i = 0; i < 10; i++)
        {
            GC.Collect(GC.MaxGeneration);
            GC.WaitForPendingFinalizers();
            GC.WaitForFullGCComplete();
            GC.Collect();
        }
    }

    private static void RenderBallDiff(bool isDaily, ExcelPackage excelPackage, List<TotalModel> totalList, ExcelWorksheet formatTpl)
    {
        using var sheetDiff = excelPackage.Workbook.Worksheets.Add("Bal-Diff");
        RenderTitle(isDaily, sheetDiff, formatTpl);
        var grandTotal = totalList.Sum(s => s.TotalRM);
        totalList.Add(new TotalModel { Name = "Bal Diff", TotalRM = grandTotal });
        sheetDiff.Cells["B5"].LoadFromCollection(totalList, true);
        sheetDiff.Cells["B5:C5"].StyleID = formatTpl.Cells["B4"].StyleID;
        sheetDiff.Cells[6, 2, sheetDiff.Dimension.End.Row, 3].StyleID = formatTpl.Cells["B5"].StyleID;
        sheetDiff.Cells[sheetDiff.Dimension.End.Row, 2, sheetDiff.Dimension.End.Row, 3].StyleID = formatTpl.Cells["B6"].StyleID;
        sheetDiff.Column(2).Width = 10;
        sheetDiff.Column(3).Width = 20;

        var filenameDiff = isDaily
            ? $"Daily Balance Breakdown DIFF for {DateTime.Today:dd-MM-yyyy}.xlsx"
            : $"Monthly Balance Breakdown DIFF for {DateTime.Today.AddMonths(-1):MM-yyyy}.xlsx";
        SaveExcelFile(isDaily, excelPackage, filenameDiff);
    }

    private static void RenderContent(IDataReader reader, ExcelWorksheet sheet, ExcelWorksheet formatTpl, out bool hasData, out decimal total)
    {
        var row = 5;
        total = 0;
        for (var col = 0; col < reader.FieldCount; col++)
        {
            sheet.Cells[row, col + 2].Value = reader.GetName(col);
            sheet.Cells[row, col + 2].StyleID = formatTpl.Cells["B4"].StyleID;
        }

        row++;
        while (reader.Read())
        {
            for (var i = 0; i < reader.FieldCount; i++)
            {
                sheet.Cells[row, i + 2].Value = reader[i];
                sheet.Cells[row, i + 2].StyleID = formatTpl.Cells["B5"].StyleID;
                if (i == reader.FieldCount - 1)
                {
                    total += Convert.ToDecimal(reader[i]);
                }
            }
            row++;
        }

        var endCol = sheet.Dimension.End.Column;
        sheet.Cells[sheet.Dimension.Address].AutoFitColumns(10, 50);
        sheet.Columns[2].Width = 25;
        sheet.View.FreezePanes(6, 1);
        for (var col = 2; col <= endCol; col++)
        {
            sheet.Columns[col].Width += 2;
        }

        hasData = row > 7;
    }

    private static void RenderTitle(bool isDaily, ExcelWorksheet sheet, ExcelWorksheet formatTpl)
    {
        sheet.View.ShowGridLines = false;
        sheet.Cells["B2"].Value = isDaily
            ? $"Daily Balance Breakdown Report For {DateTime.Today:dd MMMM, yyyy}"
            : $"Monthly Balance Breakdown Report For {DateTime.Today.AddMonths(-1):MMM yyyy}";
        sheet.Cells["B2"].StyleID = formatTpl.Cells["B2"].StyleID;
        sheet.Cells["B3"].Value = $"Generated by StarixIT on {DateTime.Now:dd MMM, yyyy hh:mm:ss tt}";
        sheet.Cells["B3"].StyleID = formatTpl.Cells["B3"].StyleID;
    }

    private static void SaveExcelFile(bool isDaily, ExcelPackage excelPackage, string fileName)
    {
        excelPackage.Workbook.Worksheets.Delete("Format");
        var name = $"{fileName}";
        var folder = isDaily ? "InternalDaily" : "InternalMonthly";
        var path = $"{AppConfigService.Config.Path}/{folder}";
        if (!Directory.Exists(path))
        {
            Directory.CreateDirectory(path);
        }

        path = $"{path}/{name}";
        excelPackage.SaveAs(new FileInfo(path), AppConfigService.Config.Password);
    }
}